// BNNana
// Layer 2 Testbench
//
// 128 binary inputs -> 32 binary outputs
//
// Expected values were calculated from the actual:
//     layer2_weights.mem
//     layer2_thresholds.mem
//
// Comparator:
//     count > threshold
