module tb_layer2;

    reg  [127:0] inputs;
    wire [31:0]  outputs;

    integer pass_count;
    integer fail_count;


    // ============================================================
    // DUT
    // ============================================================

    layer2 dut (
        .inputs(inputs),
        .outputs(outputs)
    );


    // ============================================================
    // TEST TASK
    // ============================================================

    task run_test;

        input [127:0] test_input;
        input [31:0]  expected_output;
        input integer test_number;

        begin

            inputs = test_input;

            #1;

            if (outputs === expected_output) begin

                $display(
                    "TEST %0d: PASS  INPUT=%032h  OUTPUT=%08h",
                    test_number,
                    inputs,
                    outputs
                );

                pass_count = pass_count + 1;

            end

            else begin

                $display(
                    "TEST %0d: FAIL  INPUT=%032h  EXPECTED=%08h  ACTUAL=%08h",
                    test_number,
                    inputs,
                    expected_output,
                    outputs
                );

                fail_count = fail_count + 1;

            end

        end

    endtask


    // ============================================================
    // TESTS
    // ============================================================

    initial begin

        pass_count = 0;
        fail_count = 0;

        inputs = 128'd0;

        #10;

        $display("");
        $display("============================================================");
        $display("LAYER 2 TEST");
        $display("128 INPUTS -> 32 BINARY OUTPUTS");
        $display("============================================================");


        // --------------------------------------------------------
        // TEST 1
        // --------------------------------------------------------

        run_test(
            128'h00000000000000000000000000000000,
            32'h68BD5453,
            1
        );


        // --------------------------------------------------------
        // TEST 2
        // --------------------------------------------------------

        run_test(
            128'hFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF,
            32'h6825C773,
            2
        );


        // --------------------------------------------------------
        // TEST 3
        // --------------------------------------------------------

        run_test(
            128'hAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA,
            32'h789460D3,
            3
        );


        // --------------------------------------------------------
        // TEST 4
        // --------------------------------------------------------

        run_test(
            128'h55555555555555555555555555555555,
            32'h68BDC663,
            4
        );


        // --------------------------------------------------------
        // TEST 5
        // --------------------------------------------------------

        run_test(
            128'h123456789ABCDEF00123456789ABCDEF,
            32'h683D8453,
            5
        );


        // --------------------------------------------------------
        // TEST 6
        // --------------------------------------------------------

        run_test(
            128'hD50598BC638ADF52947BCC8F3697082F,
            32'h48BDD651,
            6
        );


        // --------------------------------------------------------
        // TEST 7
        // --------------------------------------------------------

        run_test(
            128'h5B9232D4365DC077947BCC8F3697082F,
            32'hC8BCB671,
            7
        );


        // --------------------------------------------------------
        // TEST 8
        // --------------------------------------------------------

        run_test(
            128'h00000000000000000000000000000001,
            32'h689C5443,
            8
        );


        // --------------------------------------------------------
        // TEST 9
        // --------------------------------------------------------

        run_test(
            128'hFEDCBA98765432100123456789ABCDEF,
            32'h48940451,
            9
        );


        // --------------------------------------------------------
        // TEST 10
        // --------------------------------------------------------

        run_test(
            128'h947BCC8F3697082F3A86C29C07D09098,
            32'hE895C863,
            10
        );


        // ========================================================
        // FINAL RESULT
        // ========================================================

        $display("");
        $display("============================================================");
        $display("LAYER 2 VERIFICATION COMPLETE");
        $display("PASS = %0d", pass_count);
        $display("FAIL = %0d", fail_count);
        $display("============================================================");

        if (fail_count == 0)
            $display("LAYER 2 TEST PASSED");
        else
            $display("LAYER 2 TEST FAILED");

        $display("");

        #10;

        $finish;

    end

endmodule
