def load_checkpoint(path):
    if not path.is_file():
        raise FileNotFoundError(
            f"Checkpoint not found:\n{path}"
        )

    state = torch.load(
        path,
        map_location="cpu",
        weights_only=True,
    )

    if "state_dict" in state:
        state = state["state_dict"]

    # Handle checkpoints saved from DataParallel models.
    if any(key.startswith("module.") for key in state):
        state = {
            key.removeprefix("module."): value
            for key, value in state.items()
        }

    return state


def c_float(value):
    """Format a Python float as a C++ float literal."""
    value = float(value)

    if not torch.isfinite(torch.tensor(value)):
        raise ValueError(f"Non-finite parameter found: {value}")

    return f"{value:.9g}f"


def format_array(name, c_type, values, per_line=8):
    """Format a flat list as a C++ constexpr array."""
    lines = [
        f"static const {c_type} {name}[{len(values)}] = {{"
    ]

    for start in range(0, len(values), per_line):
        chunk = values[start:start + per_line]
        lines.append("    " + ", ".join(map(str, chunk)) + ",")

    lines.append("};")
    return "\n".join(lines)


def tensor_values(tensor):
    return tensor.detach().cpu().reshape(-1).tolist()


def export_model():
    state = load_checkpoint(CHECKPOINT)

    required = []
    expected_shapes = {}

    # Hidden layer weight and BatchNorm tensors.
    input_sizes = [16, 64, 128]
    output_sizes = [64, 64, 32]

    for i, (in_size, out_size) in enumerate(
        zip(input_sizes, output_sizes)
    ):
        prefix = f"layers.{i}"

        expected_shapes[f"{prefix}.linear.weight"] = (
            out_size, in_size
        )

        for name in [
            "weight",
            "bias",
            "running_mean",
            "running_var",
        ]:
            expected_shapes[f"{prefix}.bn.{name}"] = (
                out_size,
            )

    expected_shapes["output_layer.weight"] = (1, 160)

    required = list(expected_shapes)

    missing = [key for key in required if key not in state]
    if missing:
        raise KeyError(
            "Checkpoint is missing required parameters:\n"
            + "\n".join(missing)
        )

    for key, expected_shape in expected_shapes.items():
        actual_shape = tuple(state[key].shape)

        if actual_shape != expected_shape:
            raise ValueError(
                f"{key}: expected {expected_shape}, "
                f"got {actual_shape}"
            )

    sections = [
        "// Generated by scripts/export_model.py",
        "// Do not edit this file manually.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"static constexpr int INPUT_SIZE = {INPUT_SIZE};",
        "static constexpr int HIDDEN1_SIZE = 64;",
        "static constexpr int HIDDEN2_SIZE = 64;",
        "static constexpr int HIDDEN3_SIZE = 32;",
        "static constexpr int OUTPUT_SIZE = 1;",
        "static constexpr float BN_EPS = 1.0e-5f;",
        "",
    ]

    # Export each hidden layer's binary weights and BatchNorm values.
    for i, (in_size, out_size) in enumerate(
        zip(input_sizes, output_sizes)
    ):
        prefix = f"layers.{i}"
        weight_key = f"{prefix}.linear.weight"

        # Match ste.py: sign(weight), with zero mapped to +1.
        binary_weights = torch.sign(state[weight_key]).to(torch.int8)
        binary_weights[binary_weights == 0] = 1

        sections.append(
            format_array(
                f"LAYER{i}_WEIGHTS",
                "int8_t",
                tensor_values(binary_weights),
                per_line=16,
            )
        )

        for suffix, array_name in [
            ("weight", "GAMMA"),
            ("bias", "BETA"),
            ("running_mean", "RUNNING_MEAN"),
            ("running_var", "RUNNING_VAR"),
        ]:
            key = f"{prefix}.bn.{suffix}"
            values = [
                c_float(v) for v in tensor_values(state[key])
            ]

            sections.append(
                format_array(
                    f"LAYER{i}_BN_{array_name}",
                    "float",
                    values,
                    per_line=4,
                )
            )

        sections.append("")

    # Export the final binary linear layer's weights.
    output_weights = torch.sign(
        state["output_layer.weight"]
    ).to(torch.int8)
    output_weights[output_weights == 0] = 1

    sections.append(
        format_array(
            "OUTPUT_WEIGHTS",
            "int8_t",
            tensor_values(output_weights),
            per_line=16,
        )
    )

    OUTPUT_HEADER.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_HEADER.write_text(
        "\n\n".join(sections) + "\n",
        encoding="utf-8",
    )

    print("Model export successful.")
    print(f"Checkpoint: {CHECKPOINT}")
    print(f"Generated header: {OUTPUT_HEADER}")
    print("Architecture: 16 -> 64 -> 64 -> 32 -> 1")
    print("Dense concatenation: enabled")
    print("Exported: binary weights and BatchNorm parameters")


if __name__ == "__main__":
    export_model()
